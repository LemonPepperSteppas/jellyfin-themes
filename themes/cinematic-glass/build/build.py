# -*- coding: utf-8 -*-
"""Build Cinematic Glass in both shipping shapes.

Two profiles, from mostly the same sources:

  custom-css   src/*.css                     -> dist/cinematic-glass.css
               Pasted (or @import-ed) into Dashboard > Branding > Custom CSS.
               Layers ON TOP of the built-in Dark theme.

  standalone   standalone/*.css + src/*.css  -> dist/standalone/theme.css
               Dropped into <jellyfin-web>/themes/cinematic-glass/ and registered
               in config.json. REPLACES the built-in theme, so it needs the extra
               base layer in standalone/ - anything omitted is simply unstyled.

Source order is filename order (00 -> 99), so the cascade is deterministic and
adding a module means picking its number, not editing this script.

    python build/build.py                  # both profiles
    python build/build.py --profile custom-css
    python build/build.py --min            # also write .min.css
    python build/build.py --check          # lint only, write nothing (CI)
"""
import io, os, re, sys, shutil, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
THEME = os.path.dirname(HERE)
SRC = os.path.join(THEME, "src")
STANDALONE = os.path.join(THEME, "standalone")
DIST = os.path.join(THEME, "dist")

NAME = "Cinematic Glass"
SLUG = "cinematic-glass"
TARGET = "Jellyfin 10.11.x"

PROFILES = {
    # name          dirs in cascade order      output path
    "custom-css": ([SRC], os.path.join(DIST, "%s.css" % SLUG)),
    "standalone": ([STANDALONE, SRC], os.path.join(DIST, "standalone", "theme.css")),
}


def css_in(d):
    if not os.path.isdir(d):
        return []
    return [(d, f) for f in sorted(os.listdir(d)) if f.endswith(".css")]


def banner(profile, n):
    how = ("Dashboard > Branding > Custom CSS"
           if profile == "custom-css" else
           "<jellyfin-web>/themes/%s/theme.css - see standalone/INSTALL.md" % SLUG)
    return ("/*!\n"
            " * %s - a theme for %s web\n"
            " * Profile: %s -> %s\n"
            " * Built %s from %d source modules.\n"
            " * Do not edit this file; edit src/ and re-run build/build.py\n"
            " */\n" % (NAME, TARGET, profile, how, datetime.date.today().isoformat(), n))


def minify(css):
    css = re.sub(r"/\*(?!!).*?\*/", "", css, flags=re.S)   # keep the /*! banner */
    css = re.sub(r"\s+", " ", css)
    css = re.sub(r"\s*([{}:;,>~+])\s*", r"\1", css)
    return re.sub(r";}", "}", css).strip()


def lint(files):
    """Guardrails for the mistakes this theme is specifically prone to."""
    problems = []
    for d, f in files:
        text = io.open(os.path.join(d, f), encoding="utf-8").read()
        where = os.path.basename(d) + "/" + f

        # colour literals belong in 00-tokens.css and nowhere else
        if f != "00-tokens.css":
            for m in re.finditer(r"#[0-9a-fA-F]{3,8}\b|\brgba?\(", text):
                problems.append("%s:%d  colour literal outside 00-tokens.css"
                                % (where, text[:m.start()].count("\n") + 1))

        # an incomplete MUI accent family leaves every hover state Jellyfin blue
        if f.startswith("01-"):
            for fam in ("primary", "secondary", "error"):
                if ("--jf-palette-%s-main:" % fam in text
                        and "--jf-palette-%s-mainChannel:" % fam not in text):
                    problems.append("%s  sets %s-main without %s-mainChannel" % (where, fam, fam))

        if "!important" in text and not f.startswith("99-"):
            problems.append("%s  %d x !important (prefer specificity; 99-fixes.css is the exception)"
                            % (where, text.count("!important")))
    return problems


def rules_only(text):
    """The text with comments stripped - used to tell a stub from a real module."""
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S).strip()


def build(profile, want_min):
    dirs, out = PROFILES[profile]
    files = [x for d in dirs for x in css_in(d)]
    if not any(rules_only(io.open(os.path.join(d, f), encoding="utf-8").read())
               for d, f in files):
        print("  %-11s no rules written yet - nothing to build" % profile)
        return

    parts = [banner(profile, len(files))]
    for d, f in files:
        text = io.open(os.path.join(d, f), encoding="utf-8").read().strip()
        if text:
            tag = os.path.basename(d) + "/" + f
            parts.append("\n/* ---- %s %s */\n%s" % (tag, "-" * max(0, 58 - len(tag)), text))
    css = "\n".join(parts) + "\n"

    os.makedirs(os.path.dirname(out), exist_ok=True)
    io.open(out, "w", encoding="utf-8").write(css)
    print("  %-11s %-34s %6.1f KB  (%d modules)"
          % (profile, os.path.relpath(out, THEME).replace("\\", "/"), len(css) / 1024.0, len(files)))

    if want_min:
        mp = out[:-4] + ".min.css"
        mini = minify(css)
        io.open(mp, "w", encoding="utf-8").write(mini)
        print("  %-11s %-34s %6.1f KB"
              % ("", os.path.relpath(mp, THEME).replace("\\", "/"), len(mini) / 1024.0))

    # the standalone profile ships its install instructions and config entry beside it
    if profile == "standalone":
        for extra in ("INSTALL.md", "config.snippet.json"):
            src = os.path.join(STANDALONE, extra)
            if os.path.isfile(src):
                shutil.copy2(src, os.path.join(os.path.dirname(out), extra))


def main():
    args = sys.argv[1:]
    only = None
    if "--profile" in args:
        only = args[args.index("--profile") + 1]
        if only not in PROFILES:
            print("unknown profile %r; choose from %s" % (only, ", ".join(PROFILES)))
            return 2

    all_files = [x for d in (SRC, STANDALONE) for x in css_in(d)]
    problems = lint(all_files)
    for p in problems:
        print("  warn: " + p)

    if "--check" in args:
        print("%d module(s), %d warning(s)" % (len(all_files), len(problems)))
        return 1 if problems else 0

    for profile in ([only] if only else list(PROFILES)):
        build(profile, "--min" in args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
